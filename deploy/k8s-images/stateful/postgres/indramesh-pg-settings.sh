#!/bin/sh
# indramesh-pg-settings.sh — the ONE definition of the two restart-time server
# settings the own Postgres image bakes in (Phase 312.1, D-11/D-12, PGAGE-02).
#
# Sourced by (never executed directly):
#   /usr/local/bin/indramesh-postgres-entrypoint.sh             (wrapper entrypoint:
#                                                                an already-initialized
#                                                                data directory)
#   /docker-entrypoint-initdb.d/00-indramesh-server-settings.sh (fresh initdb only)
#
# Why postgresql.auto.conf: PostgreSQL reads it AFTER postgresql.conf and it
# overrides it; the PostgreSQL 18 documentation states that it is externally
# editable ("Settings in postgresql.auto.conf override those in postgresql.conf.
# External tools may also modify postgresql.auto.conf."). It is the only file
# that satisfies BOTH cases: an existing data directory that already carries a
# PG_VERSION file, and a fresh initdb. The alternative mechanisms all fail that
# requirement — postgresql.conf.sample and initdb arguments are fresh-init-only,
# and `-c` command arguments are lost the moment the run command is overridden
# and invisible in the data directory. No `command:`/`args:` exists anywhere
# for these settings (D-12).
#
# Nothing in this file may reference the system temp directory or a
# temporary-file helper: under the pod's read-only root filesystem the ONLY
# guaranteed writable path is the data directory itself, so the scratch file
# lives inside it.

# indramesh_ensure_setting <data-directory> <parameter> <value>
#
# Idempotent: the parameter ends up with EXACTLY ONE assignment in
# postgresql.auto.conf. Any existing assignment of the parameter is removed
# first. One deliberate exception: `shared_preload_libraries` is a LIST, so it is
# MERGED — the value is appended to the existing comma list unless it is already
# present, keeping every other library an operator configured (e.g.
# pg_stat_statements via ALTER SYSTEM). Replacing the list would silently drop
# those libraries on every container start. Scalar settings (`wal_level`) are
# enforced: the existing value is replaced by the given one.
#
# The rewrite goes THROUGH the existing file, so inode, ownership and mode
# survive; the scratch file is created inside the data directory and removed
# again.
indramesh_ensure_setting() {
  _indramesh_dir="${1:?data directory required}"
  _indramesh_key="${2:?parameter name required}"
  _indramesh_val="${3?parameter value required}"
  _indramesh_file="$_indramesh_dir/postgresql.auto.conf"
  _indramesh_tmp="$_indramesh_file.indramesh.$$"

  # Create the file with PostgreSQL's own header comment when it does not exist
  # yet (initdb normally creates it empty; a data directory without it is still
  # a valid input, the server reads the file when it is there).
  if [ ! -f "$_indramesh_file" ]; then
    printf '%s\n%s\n' \
      '# Do not edit this file manually!' \
      '# It will be overwritten by the ALTER SYSTEM command.' > "$_indramesh_file"
  fi

  # List-valued parameter: merge with everything already configured instead of
  # replacing it. Quoting is handled in exactly one place (below).
  _indramesh_new="$_indramesh_val"
  if [ "$_indramesh_key" = "shared_preload_libraries" ]; then
    _indramesh_old="$(sed -n "s/^[[:space:]]*${_indramesh_key}[[:space:]]*=[[:space:]]*//p" "$_indramesh_file" | tail -n 1)"
    _indramesh_old="${_indramesh_old#\'}"
    _indramesh_old="${_indramesh_old%\'}"
    _indramesh_old="$(printf '%s' "$_indramesh_old" | tr -d '[:space:]')"
    if [ -n "$_indramesh_old" ]; then
      case ",${_indramesh_old}," in
        *",${_indramesh_val},"*)
          _indramesh_new="$_indramesh_old" ;;                          # already present: unchanged
        *)
          _indramesh_new="${_indramesh_old},${_indramesh_val}" ;;      # keep the operator's libraries
      esac
    fi
    _indramesh_new="'${_indramesh_new}'"
  fi

  # Drop every existing assignment of the parameter, append exactly one.
  grep -v -E "^[[:space:]]*${_indramesh_key}[[:space:]]*=" "$_indramesh_file" > "$_indramesh_tmp" || :
  printf '%s = %s\n' "$_indramesh_key" "$_indramesh_new" >> "$_indramesh_tmp"

  # Write back through the existing file (no mv), then remove the scratch file.
  cat "$_indramesh_tmp" > "$_indramesh_file"
  rm -f "$_indramesh_tmp"
}

# The two settings live here, side by side, so both paths can never drift apart.
indramesh_write_server_settings() {
  indramesh_ensure_setting "$1" shared_preload_libraries age
  indramesh_ensure_setting "$1" wal_level logical
}

# Existing data directory (Compose today, the Kubernetes PVC after the image
# swap): applied by the wrapper entrypoint on EVERY container start, before the
# server process starts, so the settings take effect on that same start. A
# directory without PG_VERSION has not been initialized yet — this function
# deliberately changes nothing there; the fresh path below owns that case.
indramesh_apply_server_settings() {
  _indramesh_dir="${1:?data directory required}"
  [ -s "$_indramesh_dir/PG_VERSION" ] || return 0
  indramesh_write_server_settings "$_indramesh_dir"
}

# Fresh data directory: runs from the image's initdb script directory during the
# first initdb only, after initdb has created postgresql.auto.conf — too early
# for anything else would be before the file exists.
indramesh_apply_server_settings_fresh_init() {
  indramesh_write_server_settings "${1:?data directory required}"
}
